import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto('http://127.0.0.1:5173/');
 await page.getByRole('button',{name:'Explore with demo data'}).click();
 await page.getByRole('heading',{name:'A clearer picture.'}).waitFor();
 await page.getByRole('button',{name:'Add transaction',exact:true}).click();
 const dialog=page.getByRole('dialog');
 await dialog.getByLabel('Transaction name').fill('Smoke coffee');
 await dialog.getByLabel('Amount (₹)').fill('10.25');
 await dialog.getByLabel('Category',{exact:true}).selectOption('Food');
 await dialog.getByRole('button',{name:'Save transaction'}).click();
 await page.locator('nav').getByRole('button',{name:'Transactions',exact:true}).click();
 await page.getByLabel('Search transactions').fill('Smoke coffee');
 await page.getByText('Smoke coffee',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Edit Smoke coffee'}).click();
 await page.getByRole('dialog').getByLabel('Amount (₹)').fill('20.50');
 await page.getByRole('button',{name:'Save transaction',exact:true}).click();
 await page.getByText('−₹20.50',{exact:true}).waitFor();
 await page.reload();
 await page.getByRole('button',{name:'Explore with demo data'}).click();
 await page.locator('nav').getByRole('button',{name:'Transactions',exact:true}).click();
 await page.getByLabel('Search transactions').fill('Smoke coffee');
 await page.getByText('Smoke coffee',{exact:true}).waitFor();
 page.once('dialog',d=>d.accept());
 await page.getByRole('button',{name:'Delete Smoke coffee'}).click();
 await page.getByText('No transactions here yet.',{exact:false}).waitFor();
 await page.locator('nav').getByRole('button',{name:'Budgets',exact:true}).click();
 await page.getByRole('button',{name:'Set a budget'}).click();
 await page.getByRole('dialog').getByLabel('Monthly limit (₹)').fill('10');
 await page.getByRole('button',{name:'Save budget',exact:true}).click();
 await page.getByText('over limit',{exact:false}).waitFor();
 await page.locator('nav').getByRole('button',{name:'Transactions',exact:true}).click();
 await page.locator('input[type=file]').setInputFiles({name:'valid.csv',mimeType:'text/csv',buffer:Buffer.from('name,amount,type,category,date,description\nCSV coffee,24.25,Expense,Food,2026-11-02,Test')});
 await page.getByRole('button',{name:'Validate & preview'}).click();
 await page.getByText('1 valid rows · 0 issues').waitFor();
 await page.getByRole('button',{name:'Confirm import'}).click();
 await page.getByLabel('Search transactions').fill('CSV coffee');
 await page.getByText('CSV coffee',{exact:true}).waitFor();
 await page.locator('input[type=file]').setInputFiles({name:'invalid.csv',mimeType:'text/csv',buffer:Buffer.from('name,amount,type,category,date\nInvalid,0,Expense,Food,2026-11-02')});
 await page.getByRole('button',{name:'Validate & preview'}).click();
 await page.getByText('0 valid rows · 1 issues').waitFor();
 assert.equal(await page.getByRole('button',{name:'Confirm import'}).isDisabled(),true);
 await page.getByRole('button',{name:'Close dialog'}).click();
 await page.locator('nav').getByRole('button',{name:'AI Assistant'}).click();
 await page.getByRole('button',{name:'Generate insights'}).click();
 await page.getByText('Offline calculation · NVIDIA unavailable').waitFor();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Toggle navigation'}).click();
 await page.locator('nav').getByRole('button',{name:'Overview',exact:true}).click();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await page.waitForTimeout(1800);
 await page.screenshot({path:'smoke-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.waitForTimeout(1800);
 await page.screenshot({path:'smoke-desktop.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('Browser smoke passed: demo, transaction CRUD, persistence, budget warnings, CSV confirmation/validation, offline insights, mobile layout; no runtime errors.');
}finally{await browser.close()}
